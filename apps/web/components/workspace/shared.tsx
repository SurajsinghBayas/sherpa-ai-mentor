"use client";

import { motion } from "framer-motion";
import { Cpu, ShieldCheck, TriangleAlert } from "lucide-react";
import type { Mode } from "../../lib/api";
import { Sherpa, type Pose } from "../sherpa";
import { Badge } from "../ui/primitives";
import { cn } from "../../lib/utils";

export const ease = [0.22, 1, 0.36, 1] as const;

/** Tells the reader whether a model wrote this or the offline fallback did. */
export function ModeBadge({ mode, model }: { mode: Mode; model?: string | null }) {
  if (mode === "offline") {
    return (
      <Badge variant="warning" title="No language model was available; this was built directly from the code">
        <TriangleAlert /> offline fallback
      </Badge>
    );
  }
  return (
    <Badge variant="secondary" className="font-normal" title="Generated by this model, citations verified by Sherpa">
      <Cpu /> {model ? model.replace(/^[a-z0-9-]+\./i, "") : "AI-written"}
    </Badge>
  );
}

export function VerifiedBadge({ n, dropped = 0 }: { n: number; dropped?: number }) {
  return (
    <Badge
      variant={n ? "success" : "warning"}
      title={dropped ? `${dropped} unverifiable reference(s) were removed` : "Every citation exists in the indexed snapshot"}
    >
      <ShieldCheck /> {n} verified source{n === 1 ? "" : "s"}
      {dropped ? ` · ${dropped} removed` : ""}
    </Badge>
  );
}

/** Empty and loading states: Sherpa shows what the panel is for (or that it is working). */
export function EmptyState({
  busy,
  pose = "guide",
  title,
  body,
  children,
}: {
  busy?: boolean;
  pose?: Pose;
  title: string;
  body: string;
  children?: React.ReactNode;
}) {
  return (
    <div className="flex flex-col items-center justify-center gap-4 py-14 text-center" aria-busy={busy || undefined}>
      <Sherpa pose={busy ? "thinking" : pose} size={96} decorative />
      <div>
        <h3 className="font-semibold">{title}</h3>
        <p className="mx-auto mt-1 max-w-md text-sm text-muted-foreground">{body}</p>
      </div>
      {children}
    </div>
  );
}

export function SectionLabel({ children, className }: { children: React.ReactNode; className?: string }) {
  return (
    <h3 className={cn("eyebrow mb-2", className)}>
      {children}
    </h3>
  );
}

export function FadeIn({ children, delay = 0, className }: { children: React.ReactNode; delay?: number; className?: string }) {
  return (
    <motion.div
      initial={{ opacity: 0, y: 8 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ delay, duration: 0.35, ease }}
      className={className}
    >
      {children}
    </motion.div>
  );
}

export function Dots() {
  return (
    <span className="inline-flex gap-1">
      {[0, 1, 2].map((i) => (
        <motion.span
          key={i}
          className="block h-1 w-1 rounded-full bg-current"
          animate={{ y: [0, -3, 0] }}
          transition={{ duration: 0.8, delay: i * 0.15, repeat: Infinity }}
        />
      ))}
    </span>
  );
}

/** Line-numbered code block for tours. */
export function CodeBlock({ code, start }: { code: string; start: number }) {
  return (
    <pre className="scroll-thin-code overflow-x-auto bg-code py-3 font-mono text-[11.5px] leading-[1.6] text-code-foreground">
      {code.split("\n").map((ln, i) => (
        <div key={i} className="flex min-w-max pr-4">
          <span className="w-12 shrink-0 select-none pr-3 text-right text-code-muted">{start + i}</span>
          <span className="whitespace-pre">{ln || " "}</span>
        </div>
      ))}
    </pre>
  );
}

export function timeAgo(ts: number | null | undefined): string {
  if (!ts) return "";
  const s = Math.max(1, Math.round(Date.now() / 1000 - ts));
  if (s < 60) return "just now";
  if (s < 3600) return `${Math.round(s / 60)} min ago`;
  if (s < 86400) return `${Math.round(s / 3600)} h ago`;
  return `${Math.round(s / 86400)} d ago`;
}
